#!/usr/bin/env python3
"""Generates the hash manifests the port verifies the player's files against.

Reads (never writes) a folder holding one or both Daytona Championship USA
installations, finds the pristine Daytona.exe of each edition by its SHA-256,
and writes:

  src/system/exe_manifest_2017.inc, exe_manifest_2019.inc
      {va, size, sha256} for every 64 KiB chunk of the mapped image's
      file-backed bytes (headers and each section).
  src/system/rom_manifest.inc
      {path, size, sha256} of every Model 2 ROM image, which both editions share.

Only addresses, sizes and digests are written: no bytes of the game.

    python3 tools/make_manifests.py "../Daytona Championship USA"
"""
import argparse
import hashlib
import os
import struct
import sys

CHUNK = 0x10000
EDITIONS = {
    'f5d6fa896a22ca05d31754b46afdfd5361ae5fe02c08803429f1f5d9e9010deb': '2017',
    '8ba4048f9a6920e3ecdc991059301e17c53c3c605c0cc639454c14d2665d379e': '2019',
}
ROM_FOLDERS = ('rom/daytona_rom', 'rom/fv_rom')


def sections(data):
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    count = struct.unpack_from('<H', data, pe + 6)[0]
    opt_size = struct.unpack_from('<H', data, pe + 20)[0]
    opt = pe + 24
    base = struct.unpack_from('<I', data, opt + 28)[0]
    headers = struct.unpack_from('<I', data, opt + 60)[0]
    out = [('headers', 0, 0, headers)]
    for i in range(count):
        s = opt + opt_size + 40 * i
        name = data[s:s + 8].rstrip(b'\0').decode('ascii')
        vsize, rva, raw_size, raw_off = struct.unpack_from('<IIII', data, s + 8)
        out.append((name, rva, raw_off, min(vsize, raw_size)))
    return base, out


def exe_ranges(data):
    base, secs = sections(data)
    ranges = []
    for name, rva, raw_off, size in secs:
        for at in range(0, size, CHUNK):
            n = min(CHUNK, size - at)
            ranges.append((name, base + rva + at, n, hashlib.sha256(data[raw_off + at:raw_off + at + n]).digest()))
    return ranges


def c_bytes(digest):
    return ','.join('0x%02x' % b for b in digest)


def write(path, text):
    with open(path, 'w', newline='\n') as f:
        f.write(text)
    print('wrote', path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('library', help='folder holding the installation(s); read only')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'src', 'system'))
    args = ap.parse_args()

    found = {}
    rom_dirs = {}
    for dirpath, dirnames, filenames in os.walk(args.library):
        for name in filenames:
            if not name.lower().startswith('daytona.exe'):
                continue
            path = os.path.join(dirpath, name)
            with open(path, 'rb') as f:
                data = f.read()
            edition = EDITIONS.get(hashlib.sha256(data).hexdigest())
            if edition and edition not in found:
                found[edition] = (path, data)
                rom_dirs[edition] = dirpath
    if not found:
        sys.exit('no pristine Daytona.exe found under ' + args.library)

    for edition in sorted(found):
        path, data = found[edition]
        ranges = exe_ranges(data)
        lines = ['// Generated by tools/make_manifests.py from the pristine %s Daytona.exe.' % edition,
                 '// {va, size, sha256} of each 64 KiB chunk of the mapped image; no game bytes.']
        for name, va, size, digest in ranges:
            lines.append('{0x%08xu, 0x%05xu, {%s}},  // %s' % (va, size, c_bytes(digest), name))
        write(os.path.join(args.out, 'exe_manifest_%s.inc' % edition), '\n'.join(lines) + '\n')
        print('  %s: %d ranges, %d bytes' % (edition, len(ranges), sum(r[2] for r in ranges)))

    roms = None
    for edition in sorted(rom_dirs):
        entries = []
        for folder in ROM_FOLDERS:
            full = os.path.join(rom_dirs[edition], folder)
            for name in sorted(os.listdir(full)):
                p = os.path.join(full, name)
                if os.path.isfile(p) and name.endswith('.bin'):
                    with open(p, 'rb') as f:
                        blob = f.read()
                    entries.append((folder + '/' + name, len(blob), hashlib.sha256(blob).digest()))
        if roms is None:
            roms = entries
        elif roms != entries:
            sys.exit('the editions\' Model 2 ROM sets differ; the port expects them identical')
    lines = ['// Generated by tools/make_manifests.py: the Model 2 ROM images both editions ship.',
             '// {path relative to the game folder, size, sha256}; no game bytes.']
    for path, size, digest in roms:
        lines.append('{"%s", %du, {%s}},' % (path, size, c_bytes(digest)))
    write(os.path.join(args.out, 'rom_manifest.inc'), '\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
